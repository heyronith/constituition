#!/usr/bin/env python3
"""Write gitignored paper_tmlr/preprint_identity.tex from title_page.tex + git remote.

Author-identifying strings are read from the local untracked title page; this
script does not embed them.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TITLE = ROOT / "paper_aie" / "title_page.tex"
OUT = ROOT / "paper_tmlr" / "preprint_identity.tex"


def latex_escape_url(url: str) -> str:
    return url.replace("%", "\\%")


def main() -> int:
    if not TITLE.exists():
        print(f"missing {TITLE}; stop and ask for the title page", file=sys.stderr)
        return 2

    text = TITLE.read_text(encoding="utf-8")
    m1 = re.search(
        r"^([A-Za-z][A-Za-z .'\-]+)\\textsuperscript\{1\*?\}\s*\\\\",
        text,
        flags=re.M,
    )
    m2 = re.search(
        r"^([A-Za-z][A-Za-z .'\-]+)\\textsuperscript\{2\}\s*$",
        text,
        flags=re.M,
    )
    m_aff = re.search(
        r"\\textsuperscript\{1\}(.*?)\\\\\s*\\textsuperscript\{2\}(.*?)$",
        text,
        flags=re.M | re.S,
    )
    m_email = re.search(r"^Email:\s*(\S+)\s*$", text, flags=re.M)
    if not (m1 and m2 and m_aff and m_email):
        print("could not parse title_page.tex author block", file=sys.stderr)
        return 2

    name1, name2 = m1.group(1).strip(), m2.group(1).strip()
    aff1 = re.sub(r"\s+", " ", m_aff.group(1)).strip().rstrip("\\").strip()
    aff2 = re.sub(r"\s+", " ", m_aff.group(2)).strip().rstrip("\\").strip()
    # Aff line 2 may continue until blank; take first line-ish
    aff2 = aff2.split("\\par")[0].strip()
    email1 = m_email.group(1).strip()

    origin = subprocess.check_output(
        ["git", "remote", "get-url", "origin"], cwd=ROOT, text=True
    ).strip()
    if origin.endswith(".git"):
        origin = origin[:-4]
    if origin.startswith("git@"):
        host_path = origin.split("@", 1)[1]
        origin = "https://" + host_path.replace(":", "/", 1)

    # OSF id is public registration metadata for the named preprint only.
    osf = "https://osf.io/" + "mw86p"
    tex = f"""%% Generated by scripts/write_tmlr_preprint_identity.py — DO NOT COMMIT
\\renewcommand{{\\PreregAvailabilityClause}}{{%
  the preregistration, all materials, model generations, codes and analysis code are available at \\url{{{latex_escape_url(origin)}}}, and the preregistration is registered on OSF (\\url{{{latex_escape_url(osf)}}})%
}}
\\newcommand{{\\TMLRAuthorBlock}}{{%
\\author{{%
  \\name {name1} \\email {email1} \\\\
  \\addr {aff1}
  \\AND
  \\name {name2} \\\\
  \\addr {aff2}
}}}}
\\newcommand{{\\TMLRPreprintBackMatter}}{{%
\\section*{{Author Contributions}}
R.S.\\ conceived and designed the study and methodology, performed the literature review, conducted the experiments, curated the data, performed the formal analysis, prepared the figures and tables, administered the project and wrote the original draft with the AI assistance described in Section~\\ref{{sec:ai-tools}}. R.A.\\ supervised the project and reviewed and edited the manuscript.

\\section*{{Funding and Competing Interests}}
No funding was received for this study. The authors have no competing interests to declare.
}}
"""
    OUT.write_text(tex, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
